"""🔐 پیکربندی مدیران و تست‌کنندگان ربات نبردگاه.

════════════════════════════════════════════════════════════════════
                      نحوهٔ افزودن شناسه (ID) جدید
════════════════════════════════════════════════════════════════════

۱) شناسهٔ عددی خود را از @userinfobot بگیرید (یا به پیام خودت ریپلای
   کن — ربات در پنل /admin شناسه‌ها را نشان می‌دهد).

۲) عدد را به یکی از لیست‌های زیر اضافه کنید:

       DEVELOPER_IDS = [123456789]          ← مدیر کل
       TESTER_IDS    = [987654321]          ← تست‌کننده (دسترسی محدود)

۳) پس از ذخیرهٔ فایل، یک‌بار ربات را ری‌استارت کنید.

⚠️  شناسه‌ها «داینامیک» اعمال می‌شوند؛ یعنی هر دقیقه چک می‌شوند و نیازی
    به ذخیرهٔ مقدار بی‌نهایت در دیتابیس نیست. افزودن/حذف شناسه در همین
    فایل، بلافاصله پس از ری‌استارت اثر می‌کند و روی بازیکنان عادی اثری
    ندارد.
"""

# ─────────────────────────── مدیران کل (Developer) ───────────────────────────
# اختیارات کامل: سکه/انرژی/سطح/تجربه نامحدود، خرید رایگان همهٔ یگان‌ها و
# آیتم‌ها، بدون کول‌داون و بدون محدودیت انرژی، دسترسی به پنل /admin
DEVELOPER_IDS: list[int] = [
    8154313073,
]

# ──────────────────────── تست‌کننده‌ها (Tester) ─────────────────────────────
# اختیارات محدود: در اولین ورود یک بستهٔ تست بزرگ (سکه، یگان، آیتم) می‌گیرند،
# تجربهٔ دوبرابر می‌گیرند و کول‌داون حمله ندارند؛ ولی سکهٔ بی‌نهایت ندارند و
# به پنل /admin دسترسی ندارند.
TESTER_IDS: list[int] = [
    987654321,          # ← شناسهٔ آزمونگرها را اینجا بگذارید
]


def is_developer(user_id: int) -> bool:
    """آیا این کاربر مدیر کل (Developer) است؟ (بررسی داینامیک)"""
    return user_id in DEVELOPER_IDS


def is_tester(user_id: int) -> bool:
    """آیا این کاربر تست‌کننده (Tester) است؟ (بررسی داینامیک)"""
    return user_id in TESTER_IDS


def is_privileged(user_id: int) -> bool:
    """آیا کاربر حداقل تست‌کننده است؟ (مدیر یا تست‌کننده)"""
    return is_developer(user_id) or is_tester(user_id)
